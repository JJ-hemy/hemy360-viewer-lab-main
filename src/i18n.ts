const trackedText = new WeakMap<Text, { source: string; rendered: string }>();
const trackedAttributes = new WeakMap<Element, Map<string, { source: string; rendered: string }>>();
const observedRoots = new WeakSet<Node>();
let language: ViewerLanguage = "en";

function translate(source: string): string {
  if (language === "no") return norwegian[source] ?? source;
  const exact = english[source];
  if (exact) return exact;
  for (const [pattern, render] of dynamicEnglish) {
    const match = source.match(pattern);
    if (match) return render(...match.slice(1));
  }
  return source;
}

function translateText(node: Text) {
  const current = node.data;
  const previous = trackedText.get(node);
  const source = previous && current === previous.rendered ? previous.source : current;
  const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return;
  const rendered = `${match[1]}${translate(match[2])}${match[3]}`;
  trackedText.set(node, { source, rendered });
  if (current !== rendered) node.data = rendered;
}

function translateAttributes(element: Element) {
  let entries = trackedAttributes.get(element);
  if (!entries) { entries = new Map(); trackedAttributes.set(element, entries); }
  for (const name of ["aria-label", "title", "placeholder", "label", "tooltip-title", "tooltip-text"]) {
    const current = element.getAttribute(name);
    if (current === null) continue;
    const previous = entries.get(name);
    const source = previous && current === previous.rendered ? previous.source : current;
    const rendered = translate(source);
    entries.set(name, { source, rendered });
    if (current !== rendered) element.setAttribute(name, rendered);
  }
}

function visit(node: Node) {
  if (node.nodeType === Node.TEXT_NODE) { translateText(node as Text); return; }
  if (node instanceof Element) {
    if (node.matches("script, style, textarea")) return;
    translateAttributes(node);
    if (node.shadowRoot) observe(node.shadowRoot);
  }
  for (const child of node.childNodes) visit(child);
}

function observe(root: Node) {
  if (observedRoots.has(root)) return;
  observedRoots.add(root);
  visit(root);
  new MutationObserver((changes) => {
    for (const change of changes) {
      if (change.type === "characterData") translateText(change.target as Text);
      else if (change.type === "attributes") translateAttributes(change.target as Element);
      else for (const child of change.addedNodes) visit(child);
    }
  }).observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "title", "placeholder", "label", "tooltip-title", "tooltip-text"] });
}

export function initI18n() {
  const query = new URLSearchParams(location.search).get("lang");
  const stored = localStorage.getItem("hemy360-viewer-lang");
  language = query === "en" || query === "no"
    ? query
    : stored === "en" || stored === "no"
      ? stored
      : "en";
  document.documentElement.lang = language === "no" ? "nb" : "en";
  const selector = document.querySelector<HTMLSelectElement>("#viewer-language");
  if (selector) {
    selector.value = language;
    selector.addEventListener("change", () => {
      localStorage.setItem("hemy360-viewer-lang", selector.value);
      const next = new URL(location.href);
      next.searchParams.set("lang", selector.value);
      location.assign(next.href);
    });
  }
  observe(document.documentElement);
  // Some That Open custom elements attach shadow roots after the first render.
  let passes = 0;
  const timer = window.setInterval(() => {
    visit(document.documentElement);
    if (++passes >= 8) window.clearInterval(timer);
  }, 1000);
}
